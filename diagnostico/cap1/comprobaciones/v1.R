cat("--- M5 MA ---\n")
f212 <- c(0.5, rep(1,11), 0.5)/12
tr <- stats::filter(AP, f212); cat("2x12 Jul1955:", tr[79], " NAs:", sum(is.na(tr)), "\n")
tr13 <- stats::filter(AP, rep(1/13,13)); cat("13-MA equal (slider .before=6,.after=6) Jul1955:", tr13[79], "\n")
tr12 <- stats::filter(AP, rep(1/12,12)); cat("filter(y, rep(1/m,m)) Jul1955:", tr12[79], " NAs:", sum(is.na(tr12)), " first non-NA idx:", which(!is.na(tr12))[1], "\n")
cat("trend 12-MA at idx 79 equals mean(y[73:84])?", mean(v[73:84]), " mean(y[74:85])?", mean(v[74:85]),"\n")
# does 13-MA leave seasonality? compare std of detrended monthly pattern in trend
d13 <- tr13 - tr; cat("max |13MA - 2x12MA|:", max(abs(d13), na.rm=TRUE), "\n")
s13 <- tapply(as.numeric(tr13 - stats::filter(tr13, f212)), cycle(AP), mean, na.rm=TRUE); 
cat("--- M6 clasica ---\n")
dc <- decompose(AP, "multiplicative")
det <- AP/tr; raw <- tapply(as.numeric(det), cycle(AP), mean, na.rm=TRUE)
cat("sbar:", sprintf("%.6f", mean(raw)), " raw Jul:", sprintf("%.6f", raw[7]), " norm Jul:", raw[7]/mean(raw), "\n")
cat("n_k:", tapply(!is.na(as.numeric(det)), cycle(AP), sum), "\n")
cat("figure:", round(dc$figure,4), " sum4dec:", sum(round(dc$figure,4)), "\n")
cat("Jul55 T S R:", dc$trend[79], dc$figure[7], dc$random[79], "\n")
cat("ratios jul:", round(as.numeric(det[cycle(AP)==7]),3), "\n")
cat("min idx:", which.min(dc$figure), dc$figure[11], "\n")
cat("sum(is.na(trend)):", sum(is.na(decompose(AP)$trend)), "\n")
da <- decompose(AP, "additive"); cat("add Jul55 S R:", da$figure[7], da$random[79], "\n")
jul <- v[cycle(AP)==7]; cat("jul - annual mean:", round(jul - niv,1), "\n")
cat("0.2266*niv1949, 0.2266*niv1960, 0.2266*T jul49:", (dc$figure[7]-1)*niv[1], (dc$figure[7]-1)*niv[12], (dc$figure[7]-1)*dc$trend[7], "\n")
cat("sd resid add by yr:", round(tapply(as.numeric(da$random), yr, sd, na.rm=TRUE),1), "\n")
cat("--- log-additive classical vs multiplicative ---\n")
dl <- decompose(log(AP), "additive"); cat("exp(fig log) jul:", exp(dl$figure[7]), " mult jul:", dc$figure[7], "\n")
cat("max |exp(trend log) - trend mult|:", max(abs(exp(dl$trend)-dc$trend), na.rm=TRUE), "\n")
