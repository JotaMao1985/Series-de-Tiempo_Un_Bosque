cat("--- M4 tabla ---\n")
yr <- floor(time(AP)); v <- as.numeric(AP)
niv <- tapply(v, yr, mean); amp <- tapply(v, yr, function(z) max(z)-min(z))
print(round(cbind(niv, amp, pct=100*amp/niv),1))
