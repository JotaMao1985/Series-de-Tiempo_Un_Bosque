ayuda <- function(tema, paquete = NULL) {
  h <- if (is.null(paquete)) do.call(help, list(tema)) else do.call(help, list(tema, package = paquete))
  if (length(h) > 1) h <- h[1]
  f <- utils:::.getHelpFile(h)
  tf <- tempfile(); tools::Rd2txt(f, out = tf, options = list(underline_titles = FALSE))
  gsub("\\s+", " ", paste(readLines(tf), collapse = " "))
}
