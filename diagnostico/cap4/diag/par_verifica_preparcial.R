# de opción del preparcial del Corte II (preparcial-corte-2.html), por ítem.
r <- function(...) cat(sprintf(...), "\n")
r("a#1  r1 de un MA(1) con theta_R = -0.45: %.4f", -0.45/(1+0.45^2))
r("a#2  raíces de 1-0.8B+0.15B^2: %s", paste(round(1/Re(polyroot(c(1,-0.8,0.15))),4), collapse=" "))
r("a#6  fracción de gamma0 alcanzada a h=12 por un AR(1) phi=0.8: %.4f", 1-0.8^24)
r("b#1  phi2 = %.1f", -(-0.8*0.5))
r("b#2  rho1 = %.4f", (-0.5 + -0.5*0.3)/(1+0.25+0.09))
r("b#3  1.96*sqrt(gamma0) = %.3f", 1.96*sqrt(4*(1+2*0.6*-0.3+0.09)/(1-0.36)))
r("b#4  theta = %.1f", 0.20 - 0.18/0.20)
r("b#5  sigma2 = %.4f", 15.04*(1-0.632^2))
rr <- c(-0.020,-0.191,0.176,0.061); Q <- 100*102*sum(rr^2/(100-1:4))
r("b#6  Q(4) = %.3f  p(gl 2) = %.4f", Q, pchisq(Q,2,lower.tail=FALSE))
r("b#7  yhat = %.3f", 0.4101*276.63 + 0.5899*285.10)
r("b#8  deriva = %.4f", (565.7-350)/59)
r("b#9  AICc = %.3f", -2*-622.58 + 8 + 2*4*5/(119-4-1))
y1 <- 98.20 + 0.4863*1.56; r("b#10 yhat2 = %.4f", y1 + 0.4863*(y1-98.20))
r("b#11 semiancho = %.3f  (caminata %.3f)", 1.96*2.584*sqrt(1+2*0.5134^2), 1.96*2.584*sqrt(3))
r("b#12 semiancho80 = %.3f", 1.282*32.41*2)
r("c#1  gamma0: %.4f y %.4f; 1/theta = %.4f", 0.9166*(1+0.6045^2), 0.3350*(1+1.6542^2), 1/0.6045)
r("c#4  phi1+phi2 = %.4f; producto de módulos = %.4f frente a 1/|phi2| = %.4f", 1.2894-0.3012, 1.0173*3.2638, 1/0.3012)
r("c#5  Var(diff) teórica 2*gamma0*(1-r1) = %.2f (publicada 148.18)", 2*273.82*(1-0.729))
r("s#1  gamma0 AR(2) = %.4f", 2*(1+0.35)/((1-0.35)*((1+0.35)^2-0.6^2)))
pi <- c(1, -(0.5+0.4)); pi[3] <- -0.4*pi[2]; r("s#2  peso de y_{t-2} = -pi_2 = %.2f", -pi[3])
r("s#3  t de phi3 = %.2f", 0.0892/0.0912)
r("s#5  BIC = %.3f", -2*-193.23 + 2*log(100))
psi <- c(1, 1.4, 1+0.4+0.16); r("s#6  semiancho = %.3f", 1.96*2*sqrt(sum(psi^2)))
