suppressMessages(library(forecast))
guerrero <- function(y, lambda, m = frequency(y)) {
  bloques  <- matrix(y[1:(m * (length(y) %/% m))], nrow = m)
  cociente <- apply(bloques, 2, sd) / colMeans(bloques)^(1 - lambda)
  sd(cociente) / mean(cociente)
}
